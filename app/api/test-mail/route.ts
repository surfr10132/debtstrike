import { NextResponse } from "next/server";
import { saveSession } from "@/lib/session-store";
import { generateLetterHtml } from "@/lib/generate-letter-html";
import { LetterEditable, LetterEditableExtraServiceEnum } from "@lob/lob-typescript-sdk";
import lettersApi from "@/lib/lob";
import { SessionPayload } from "@/lib/types";

/**
 * GET /api/test-mail
 *
 * Test route — creates a fake session payload and sends it through Lob's TEST environment.
 * No real mail is sent, no charges. Just validates the full pipeline works.
 *
 * DELETE THIS ROUTE BEFORE GOING LIVE.
 */
export async function GET() {
  try {
    // Create a test payload
    const testPayload: SessionPayload = {
      extractedData: {
        collectorName: "Test Debt Collector Inc.",
        collectorAddress: "123 Collection Ave, Suite 400, San Francisco, CA 94105",
        accountNumber: "TEST-12345",
        amountClaimed: "$1,500.00",
        originalCreditor: "Original Bank Corp",
        isThirdPartyCollector: true,
        collectorTypeConfidence: "high",
        recipientName: "John Doe",
        recipientStreetAddress: "456 Consumer St",
        recipientCity: "Los Angeles",
        recipientState: "CA",
        recipientZip: "90001",
        recipientPhone: "(555) 123-4567",
      },
      userInfo: {
        fullName: "John Doe",
        streetAddress: "456 Consumer St",
        city: "Los Angeles",
        state: "CA",
        zip: "90001",
        phone: "(555) 123-4567",
        ssnLast4: "1234",
        dob: "1990-01-15",
      },
      generatedLetter: {
        letterText: `John Doe
456 Consumer St
Los Angeles, CA 90001

May 7, 2026

Test Debt Collector Inc.
123 Collection Ave, Suite 400
San Francisco, CA 94105

Re: Account #TEST-12345

Dear Test Debt Collector Inc.,

This is a test letter generated by DebtStrike.io to verify the Lob certified mail integration.

This letter serves as a formal request for debt validation pursuant to the Fair Debt Collection Practices Act (FDCPA), 15 U.S.C. § 1692g. I am exercising my right to request verification of the alleged debt referenced above.

Please provide the following documentation within thirty (30) days of receipt of this letter:

1. Verification of the amount claimed, including an itemized accounting of all charges.
2. The name and address of the original creditor.
3. A copy of the original signed agreement or contract.
4. Proof that you are licensed to collect debts in the State of California.

Additionally, pursuant to 15 U.S.C. § 1692c(c), this letter serves as my formal notice that I revoke any and all consent previously given to contact me by telephone. You are hereby directed to cease all telephone communications immediately.

Until you provide proper validation of this debt, you must cease all collection activity, including but not limited to reporting this account to any consumer reporting agency.

Sincerely,

John Doe`,
        date: "May 7, 2026",
      },
    };

    // Save session
    const payloadId = await saveSession(testPayload);

    // Generate HTML letter for Lob
    const letterHtml = generateLetterHtml(testPayload);

    // Send via Lob TEST environment — use real deliverable addresses
    const letterData = new LetterEditable({
      description: `[TEST] DebtStrike - John Doe to Test Debt Collector Inc.`,
      to: {
        name: "Test Debt Collector Inc.",
        address_line1: "185 Berry St",
        address_line2: "Suite 6100",
        address_city: "San Francisco",
        address_state: "CA",
        address_zip: "94107",
        address_country: "US",
      },
      from: {
        name: "John Doe",
        address_line1: "210 King St",
        address_city: "San Francisco",
        address_state: "CA",
        address_zip: "94107",
        address_country: "US",
      },
      file: letterHtml,
      color: false,
      extra_service: LetterEditableExtraServiceEnum.CertifiedReturnReceipt,
      use_type: "operational",
      metadata: {
        source: "debtstrike_test",
        payload_id: payloadId,
      },
    });

    const lobResponse = await lettersApi.create(letterData);

    return NextResponse.json({
      success: true,
      message: "Test letter created in Lob TEST mode — no real mail sent.",
      lobLetterId: lobResponse?.id,
      trackingNumber: lobResponse?.tracking_number,
      expectedDeliveryDate: lobResponse?.expected_delivery_date,
      url: lobResponse?.url,
      carrier: lobResponse?.carrier,
    });
  } catch (error: unknown) {
    console.error("Test mail error:", error);
    const errMsg = error instanceof Error ? error.message : "Unknown error";
    return NextResponse.json({ error: errMsg }, { status: 500 });
  }
}
